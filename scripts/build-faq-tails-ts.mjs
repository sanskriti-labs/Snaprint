// One-off build script — scans content/pseo/faq-tails/*.json and emits
// content/pseo/faq-tails.ts so faqs.ts can import the tails as a typed map.
// Run from repo root: `node scripts/build-faq-tails-ts.mjs`
//
// Mirrors scripts/build-bodies-ts.mjs: per-entity source files compile to
// one generated module, keyed by `{kind}-{slug}` filename.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const tailsDir = path.join(repoRoot, "content", "pseo", "faq-tails");
const outFile = path.join(repoRoot, "content", "pseo", "faq-tails.ts");

const files = fs
  .readdirSync(tailsDir)
  .filter((f) => f.endsWith(".json"))
  .sort();

const entries = [];
for (const f of files) {
  const key = f.replace(/\.json$/, "");
  if (!/^(area|college|city)-[a-z0-9-]+$/.test(key)) {
    throw new Error(`faq-tails filename "${f}" doesn't match "{kind}-{slug}.json"`);
  }
  const raw = fs.readFileSync(path.join(tailsDir, f), "utf8");
  let faqs;
  try {
    faqs = JSON.parse(raw);
  } catch (err) {
    throw new Error(`Invalid JSON in content/pseo/faq-tails/${f}: ${err.message}`);
  }
  if (!Array.isArray(faqs) || faqs.some((x) => typeof x.q !== "string" || typeof x.a !== "string")) {
    throw new Error(`content/pseo/faq-tails/${f} must be an array of {q, a} objects`);
  }
  entries.push({ key, faqs });
}

const banner =
  `// AUTO-GENERATED by scripts/build-faq-tails-ts.mjs — do not hand-edit.\n` +
  `// Run \`node scripts/build-faq-tails-ts.mjs\` after editing any .json file\n` +
  `// under content/pseo/faq-tails/. Source of truth is the .json files; this\n` +
  `// file is rebuilt from them.\n\n` +
  `import type { Faq } from "./faqs";\n\n` +
  `export const faqTails: Record<string, Faq[]> = {\n`;

const lines = entries
  .map((e) => `  ${JSON.stringify(e.key)}: ${JSON.stringify(e.faqs)},\n`)
  .join("");

const footer = `};\n`;

fs.writeFileSync(outFile, banner + lines + footer, "utf8");

console.log(`[build-faq-tails-ts] wrote ${entries.length} entries → ${path.relative(repoRoot, outFile)}`);
