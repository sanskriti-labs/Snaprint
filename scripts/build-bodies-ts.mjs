// One-off build script — scans content/pseo/bodies/*.md and emits
// content/pseo/bodies.ts so Next.js can import the bodies as a typed map.
// Run from repo root: `node scripts/build-bodies-ts.mjs`
//
// We keep this in scripts/ (not content/pseo/) so it can use Node's fs/path
// APIs without polluting the import graph. The emitted bodies.ts is the only
// artifact the React side sees.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const bodiesDir = path.join(repoRoot, "content", "pseo", "bodies");
const outFile = path.join(repoRoot, "content", "pseo", "bodies.ts");

const files = fs
  .readdirSync(bodiesDir)
  .filter((f) => f.endsWith(".md"))
  .sort();

function escapeTs(s) {
  // Escape backslash, backtick, and template-literal interpolation so the
  // emitted body string is a valid TS template literal.
  return s
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function wc(s) {
  // Cheap word count: whitespace-separated tokens, ignoring frontmatter.
  return s.trim() === "" ? 0 : s.trim().split(/\s+/).length;
}

const entries = [];
for (const f of files) {
  const raw = fs.readFileSync(path.join(bodiesDir, f), "utf8");
  const parsed = matter(raw);
  const fm = parsed.data || {};
  const body = parsed.content || "";
  const key = `${fm.kind}-${fm.slug}`;
  if (!fm.kind || !fm.slug || !fm.name) {
    throw new Error(`Missing frontmatter in ${f}: kind=${fm.kind} slug=${fm.slug} name=${fm.name}`);
  }
  entries.push({
    key,
    kind: fm.kind,
    slug: fm.slug,
    name: fm.name,
    city: fm.city ?? "",
    priority: Boolean(fm.priority),
    wordCount: wc(body),
    markdown: body,
  });
}

const banner =
  `// AUTO-GENERATED by scripts/build-bodies-ts.mjs — do not hand-edit.\n` +
  `// Run \`node scripts/build-bodies-ts.mjs\` after editing any .md file under\n` +
  `// content/pseo/bodies/. Source of truth is the .md files; this file is rebuilt\n` +
  `// from them.\n\n` +
  `export type BodyKind = "area" | "college" | "city";\n\n` +
  `export type BodyEntry = {\n` +
  `  kind: BodyKind;\n` +
  `  slug: string;\n` +
  `  name: string;\n` +
  `  city: string;\n` +
  `  priority: boolean;\n` +
  `  wordCount: number;\n` +
  `  markdown: string;\n` +
  `};\n\n` +
  `export const bodies: Record<string, BodyEntry> = {\n`;

const lines = entries
  .map((e) => {
    return (
      `  ${JSON.stringify(e.key)}: {\n` +
      `    kind: ${JSON.stringify(e.kind)},\n` +
      `    slug: ${JSON.stringify(e.slug)},\n` +
      `    name: ${JSON.stringify(e.name)},\n` +
      `    city: ${JSON.stringify(e.city)},\n` +
      `    priority: ${e.priority},\n` +
      `    wordCount: ${e.wordCount},\n` +
      `    markdown: \`${escapeTs(e.markdown)}\`,\n` +
      `  },\n`
    );
  })
  .join("");

const footer = `};\n`;

fs.writeFileSync(outFile, banner + lines + footer, "utf8");

console.log(`[build-bodies-ts] wrote ${entries.length} entries → ${path.relative(repoRoot, outFile)}`);
